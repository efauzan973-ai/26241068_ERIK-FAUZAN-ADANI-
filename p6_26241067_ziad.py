a = int(input("digit A: "))
b = int(input("digit B: "))

kondisi_1 = a >= 5
kondisi_2 = b >= 5

print("kondisi 1: ", kondisi_1)
print("kondisi 2: ", kondisi_2)

print("NOT: ", not kondisi_1)
print("AND: ", kondisi_1 and kondisi_2)
print("OR: ", kondisi_1 or kondisi_2)
print("XOR: ", kondisi_1 ^ kondisi_2)